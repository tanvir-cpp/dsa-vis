// Optional WASM acceleration layer with graceful TS fallback.
//
// dsa-core exposes wasm-bindgen functions (*_js) returning JsValue
// (already JS values via serde-wasm-bindgen). This loader never throws
// when pkg is missing (not yet built) — it returns null so callers
// transparently use the TS fallback generators.

export interface WasmStatus {
  loaded: boolean;
  error: string | null;
}

let pkg: any = null;
let loadPromise: Promise<any | null> | null = null;
let loadError: string | null = null;

export async function loadWasm(): Promise<any | null> {
  if (pkg) return pkg;
  if (loadPromise) return loadPromise;
  loadPromise = (async (): Promise<any | null> => {
    try {
      // @ts-ignore - ../pkg is generated by wasm-pack; absent until built
      const mod = await import(/* @vite-ignore */ '../pkg/dsa_core.js').catch(() => null);
      if (!mod) {
        loadError = 'WASM pkg not built yet';
        return null;
      }
      try {
        if (typeof mod.default === 'function') {
          await mod.default();
        }
      } catch (e) {
        loadError = e instanceof Error ? e.message : String(e);
        return null;
      }
      pkg = mod;
      loadError = null;
      return pkg;
    } catch (e) {
      loadError = e instanceof Error ? e.message : String(e);
      return null;
    }
  })();
  return loadPromise;
}

export function getWasm(): any | null {
  return pkg;
}

export function getWasmStatus(): WasmStatus {
  return { loaded: pkg !== null, error: loadError };
}

export async function wasmSteps(fn: string, ...args: unknown[]): Promise<any[] | null> {
  const w = await loadWasm();
  if (!w) return null;
  const f = w[fn];
  if (typeof f !== 'function') return null;
  try {
    const raw = await f(...args);
    if (raw == null) return null;
    if (typeof raw === 'string') {
      try {
        const parsed: unknown = JSON.parse(raw);
        return Array.isArray(parsed) ? (parsed as any[]) : null;
      } catch {
        return null;
      }
    }
    if (Array.isArray(raw)) return raw as any[];
    return null;
  } catch {
    return null;
  }
}
